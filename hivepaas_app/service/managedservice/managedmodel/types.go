package managedmodel

import (
	"time"

	"github.com/hivepaas/hivepaas/hivepaas_app/entity"
	"github.com/hivepaas/hivepaas/hivepaas_app/service/specservice/specmodel"
)

// Archive is where an engine's backups go, resolved for it by the caller: the
// credentials decrypted, the prefix chosen. Exactly one of S3 and Volume is set.
type Archive struct {
	S3     *S3Archive
	Volume *VolumeArchive
}

type S3Archive struct {
	Endpoint       string
	Region         string
	Bucket         string
	Prefix         string
	AccessKey      string
	SecretKey      string
	ForcePathStyle bool
}

// VolumeArchive is a volume backup repository's directory, mounted into the
// app: the repository's cluster-volume setting and the path inside it.
type VolumeArchive struct {
	VolumeID string
	Subpath  string
}

// Options are what the person creating the app chose, the template's defaults
// filled in. A zero field takes the engine's default.
type Options struct {
	ArchiveTimeout      time.Duration
	RetainFull          int
	BaseBackupSchedule  string
	RestoreTestSchedule string
	RestoreTestQuery    string
	// DumpRepo is the backup repository the database is dumped into, empty for
	// no dumps; DumpSchedule is when.
	DumpRepo     string
	DumpSchedule string
}

// PrepareReq is an app's rendered document, before it is built, and what the
// engine needs to add to it.
type PrepareReq struct {
	Doc *specmodel.AppDoc
	// Version is the template version, the major line: "17", "18".
	Version string
	Archive *Archive
	// EncryptionKey is the key the engine encrypts its backups with, generated by
	// the caller.
	EncryptionKey string
	Options       *Options
	// Restore makes the app a restore of another managed database, nil for a new
	// one.
	Restore *RestoreSource

	// OwnedEnv is set by PrepareDoc: the variables it added, which the app may
	// not change afterwards.
	OwnedEnv []string
}

// ConfigureReq is the app being provisioned, the settings its document was
// built into, and the request PrepareDoc was given.
type ConfigureReq struct {
	App      *entity.App
	Prepared *PrepareReq
	// Storage is the archive as the engine's setting records it: references, not
	// credentials.
	Storage  entity.ManagedStorage
	Settings []*entity.Setting
	Now      time.Time
}

// ConfigureResp is the settings the engine adds to the app: its own and its
// scheduled jobs.
type ConfigureResp struct {
	Settings []*entity.Setting
}

// SettingsChange is what a person changes of a managed app's settings: a nil
// field is left as it is, and an empty query clears it.
type SettingsChange struct {
	RetainFull          *int
	BaseBackupSchedule  *string
	RestoreTestSchedule *string
	RestoreTestQuery    *string
	RestoreTest         *RestoreTestChange
	// DumpRepo is the backup repository dumps go into: empty turns them off.
	DumpRepo     *string
	DumpSchedule *string
}

// RestoreTestChange moves the restore test: into the verifier app given, or,
// with none, back into the database's container.
type RestoreTestChange struct {
	Verifier *entity.App
	// NodeID is the node the verifier's volume is on, empty for a volume pinned
	// by label.
	NodeID string
	// KeyAuth is the narrower key the verifier reads the archive with, empty for
	// the database's own.
	KeyAuth entity.ObjectID
}

// ReconfigureReq is a managed app with its setting, the jobs its engine made by
// id, and the change asked for.
type ReconfigureReq struct {
	App *entity.App
	// ManagedID is the app-managed setting's id: what a job the change makes is
	// managed by.
	ManagedID string
	Managed   *entity.AppManagedSettings
	Jobs      map[string]*entity.Setting
	Change    *SettingsChange
	Now       time.Time
}

// ReconfigureResp is the jobs the change rewrote, and of those, the ones whose
// schedule moved, which are scheduled again; and the jobs it made and the ones
// it removes. The setting itself is changed in place.
type ReconfigureResp struct {
	Changed     []*entity.Setting
	Rescheduled []*entity.Setting
	Created     []*entity.Setting
	Deleted     []*entity.Setting
}

// VerifierSpec is what an engine's verifier app runs: a command that idles, for
// the restore test to run in, and where its scratch volume is mounted.
type VerifierSpec struct {
	Command    string
	ScratchDir string
}

// RestoreSource is what a database restored into a new app recovers from: the
// source's archive, which it only reads, the key the archive is encrypted with,
// and the target, a point resolved to its LSN.
type RestoreSource struct {
	SourceAppID   string
	Archive       *Archive
	EncryptionKey string
	Target        entity.ManagedRestoreTarget
	// PointAt is when the target point was made, for a restore to a point: the
	// base backup fetched is the latest that starts before it.
	PointAt time.Time
}

// FinishRestoreReq is a restored app's setting, and its variables, secrets and
// setting mounts, once it has recovered and its first base backup is taken.
type FinishRestoreReq struct {
	Managed  *entity.AppManagedSettings
	Settings []*entity.Setting
	Now      time.Time
}

// FinishRestoreResp is what the app keeps no more of what it was restored with:
// its settings changed and deleted, and the targets of the service's mounts to
// remove. The engine's setting is changed in place, and marked ready.
type FinishRestoreResp struct {
	Changed      []*entity.Setting
	Deleted      []*entity.Setting
	MountTargets []string
	// EnvKeys are the variables to take off the service.
	EnvKeys []string
}

// RecoveryCheck is how a restore asks a restored app whether its recovery has
// ended: Command, run in its task, exits 0 once the server is up and promoted,
// RecoveryExitRecovering while it is starting or recovering, and anything else
// when the recovery failed, having printed why.
type RecoveryCheck struct {
	Command string
}

// RecoveryExitRecovering is EX_TEMPFAIL: ask again later.
const RecoveryExitRecovering = 75

// RetentionReq is a nightly run's first step done: the engine's setting, what
// the step wrote - the base backups kept, the new one among them - and now.
type RetentionReq struct {
	Managed *entity.AppManagedSettings
	Outputs map[string]string
	Now     time.Time
}

// Retention is the nightly run's second step: the arguments the job's command
// runs with, and the oldest base backup it keeps, empty when it deletes
// nothing.
type Retention struct {
	Args     string
	Boundary string
}

// MarkCommand makes a restore point: Command, run in the database's task,
// prints the point's LSN once the WAL it is in is archived, and gives up after
// Timeout, exiting MarkExitNotArchived.
type MarkCommand struct {
	Command string
	Timeout time.Duration
}

// MarkExitNotArchived is EX_TEMPFAIL: the point is made, but the WAL it is in
// was not archived in time, so it cannot be restored to yet.
const MarkExitNotArchived = 75

// ReplicaReq is a replica about to be made of a primary: the primary, its
// engine's setting, the replica's key, and the paths the primary's setting
// mounts put files at, which say what its scripts can do.
type ReplicaReq struct {
	Primary    *entity.App
	Managed    *entity.AppManagedSettings
	Key        string
	MountPaths []string
}

// ReplicaSpec is what a replica is given beside the primary's settings, copied:
// variables, the replication password as a file at PasswordFile from the secret
// SecretName, and its data volume at DataTarget. Allow is the command that lets
// replicas into the primary, run there with the password on its stdin.
type ReplicaSpec struct {
	Env          [][2]string
	SecretName   string
	PasswordFile string
	DataTarget   string
	Allow        *entity.CommandTemplate
}
