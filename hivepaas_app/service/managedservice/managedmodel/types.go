package managedmodel

import (
	"time"

	"github.com/hivepaas/hivepaas/hivepaas_app/entity"
	"github.com/hivepaas/hivepaas/hivepaas_app/service/specservice/specmodel"
)

// Archive is where an engine's backups go, resolved for it by the caller: the
// credentials decrypted, the prefix chosen. Exactly one of S3 and Volume is set.
type Archive struct {
	S3     *S3Archive
	Volume *VolumeArchive
}

type S3Archive struct {
	Endpoint       string
	Region         string
	Bucket         string
	Prefix         string
	AccessKey      string
	SecretKey      string
	ForcePathStyle bool
}

// VolumeArchive is a volume backup repository's directory, mounted into the
// app: the repository's cluster-volume setting and the path inside it.
type VolumeArchive struct {
	VolumeID string
	Subpath  string
}

// Options are what the person creating the app chose, the template's defaults
// filled in. A zero field takes the engine's default.
type Options struct {
	ArchiveTimeout      time.Duration
	RetainFull          int
	BaseBackupSchedule  string
	RestoreTestSchedule string
	RestoreTestQuery    string
}

// PrepareReq is an app's rendered document, before it is built, and what the
// engine needs to add to it.
type PrepareReq struct {
	Doc *specmodel.AppDoc
	// Version is the template version, the major line: "17", "18".
	Version string
	Archive *Archive
	// EncryptionKey is the key the engine encrypts its backups with, generated by
	// the caller.
	EncryptionKey string
	Options       *Options

	// OwnedEnv is set by PrepareDoc: the variables it added, which the app may
	// not change afterwards.
	OwnedEnv []string
}

// ConfigureReq is the app being provisioned, the settings its document was
// built into, and the request PrepareDoc was given.
type ConfigureReq struct {
	App      *entity.App
	Prepared *PrepareReq
	// Storage is the archive as the engine's setting records it: references, not
	// credentials.
	Storage  entity.ManagedStorage
	Settings []*entity.Setting
	Now      time.Time
}

// ConfigureResp is the settings the engine adds to the app: its own and its
// scheduled jobs.
type ConfigureResp struct {
	Settings []*entity.Setting
}

// SettingsChange is what a person changes of a managed app's settings: a nil
// field is left as it is, and an empty query clears it.
type SettingsChange struct {
	RetainFull          *int
	BaseBackupSchedule  *string
	RestoreTestSchedule *string
	RestoreTestQuery    *string
	RestoreTest         *RestoreTestChange
}

// RestoreTestChange moves the restore test: into the verifier app given, or,
// with none, back into the database's container.
type RestoreTestChange struct {
	Verifier *entity.App
	// NodeID is the node the verifier's volume is on, empty for a volume pinned
	// by label.
	NodeID string
	// KeyAuth is the narrower key the verifier reads the archive with, empty for
	// the database's own.
	KeyAuth entity.ObjectID
}

// ReconfigureReq is a managed app with its setting, the jobs its engine made by
// id, and the change asked for.
type ReconfigureReq struct {
	App     *entity.App
	Managed *entity.AppManagedSettings
	Jobs    map[string]*entity.Setting
	Change  *SettingsChange
}

// ReconfigureResp is the jobs the change rewrote, and of those, the ones whose
// schedule moved, which are scheduled again. The setting itself is changed in
// place.
type ReconfigureResp struct {
	Changed     []*entity.Setting
	Rescheduled []*entity.Setting
}

// VerifierSpec is what an engine's verifier app runs: a command that idles, for
// the restore test to run in, and where its scratch volume is mounted.
type VerifierSpec struct {
	Command    string
	ScratchDir string
}
